/* ── helpers ─────────────────────────────────────────────────── */
function mkMonthly(
  baseUsage: number,
  trend: 'declining' | 'stable' | 'growing',
): MonthlyPoint[] {
  const months = [
    '24.04',
    '24.05',
    '24.06',
    '24.07',
    '24.08',
    '24.09',
    '24.10',
    '24.11',
    '24.12',
    '25.01',
  ];
  return months.map((m, i) => {
    const usageMult =
      trend === 'declining'
        ? 1 - i * 0.05
        : trend === 'growing'
          ? 1 + i * 0.03
          : 1 + (Math.random() - 0.5) * 0.06;
    return {
      month: m,
      usage: Math.round(baseUsage * usageMult * (0.92 + Math.random() * 0.16)),
    };
  });
}

